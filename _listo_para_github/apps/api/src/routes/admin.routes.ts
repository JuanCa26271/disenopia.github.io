import {Router} from 'express';
import rateLimit from 'express-rate-limit';
import {createExtra,createProduct,changeOrderStatus, dashboard,deleteExtra,deleteProduct,generateTabloid,listExtras,listProducts,updateExtra,updateProduct,getWorkshopSettings,updateWorkshopSettings} from '../controllers/admin.controller';
import {login,loginSchema,logout,session,changePassword,changePasswordSchema} from '../controllers/auth.controller';
import {requireAdmin,requireSameOrigin,requirePasswordRotation} from '../middleware/auth.middleware';
import {validateBody} from '../middleware/validate';
import {getAdminAsset,uploadAdminAsset,uploadPhotoMiddleware} from '../controllers/assets.controller';
const router=Router();
const loginLimiter=rateLimit({windowMs:30*60*1000,max:5,skipSuccessfulRequests:true,standardHeaders:true,legacyHeaders:false,message:{error:'Too many failed login attempts. Try again in 30 minutes.'}});
router.post('/login',requireSameOrigin,loginLimiter,validateBody(loginSchema),login);
router.use(requireAdmin);
router.use(requireSameOrigin);
router.post('/logout',logout);
router.post('/change-password',validateBody(changePasswordSchema),changePassword);
router.get('/session',session);
router.use(requirePasswordRotation);
router.post('/assets/:purpose',rateLimit({windowMs:60*60*1000,max:60,standardHeaders:true,legacyHeaders:false}),uploadPhotoMiddleware,uploadAdminAsset);
router.get('/assets/:asset_id',getAdminAsset);
router.get('/dashboard-calendar',dashboard);
router.get('/products',listProducts);
router.post('/products',createProduct);
router.put('/products/:id',updateProduct);
router.delete('/products/:id',deleteProduct);
router.get('/extras',listExtras);
router.post('/extras',createExtra);
router.put('/extras/:id',updateExtra);
router.delete('/extras/:id',deleteExtra);
router.patch('/orders/:ticket_code/status',changeOrderStatus);
router.get('/workshop-settings',getWorkshopSettings);
router.put('/workshop-settings',updateWorkshopSettings);
router.post('/print/generate-tabloid',generateTabloid);
export default router;
