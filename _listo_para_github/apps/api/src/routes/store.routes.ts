import {Router} from 'express';
import rateLimit from 'express-rate-limit';
import {validateBody} from '../middleware/validate';
import {asyncRoute} from '../middleware/errors';
import {catalog,checkout,checkoutSchema,downloadTicket,quote,cartSchema,ticket} from '../controllers/store.controller';
import {prisma} from '../lib/prisma';
import {getPhoto,uploadCustomerPhoto,uploadPhotoMiddleware} from '../controllers/assets.controller';
const router=Router();
const storeLimiter=rateLimit({windowMs:60_000,max:90,standardHeaders:true,legacyHeaders:false,message:{error:'Too many requests'}});
router.use(storeLimiter);
router.get('/catalog',catalog);
router.post('/assets',rateLimit({windowMs:60*60*1000,max:20,standardHeaders:true,legacyHeaders:false}),uploadPhotoMiddleware,uploadCustomerPhoto);
router.get('/assets/:asset_id',getPhoto);
router.post('/calculate-quote-and-date',validateBody(cartSchema),quote);
router.post('/checkout',validateBody(checkoutSchema),checkout);
router.get('/ticket/:ticket_code',ticket);
router.get('/ticket/:ticket_code/pdf',downloadTicket);
router.get('/health',asyncRoute(async(_req,res)=>{await prisma.$queryRaw`SELECT 1`;res.json({status:'ok'});}));
export default router;
